#!/usr/bin/env bash
# BEGIN USAGE
# Auditable full-factorial screening runs
#
# Usage:
#   ./run_full_factorial.sh --task sharks --prompt-version v0 --preflight-only
#   ./run_full_factorial.sh --task sharks --prompt-version v0 \
#     --spend-ceiling "$SPEND_CEILING_USD"
#   ./run_full_factorial.sh --task animals --prompt-version v0 \
#     --spend-ceiling "$SPEND_CEILING_USD"
#   ./run_full_factorial.sh --task sharks --prompt-version v0 \
#     --spend-ceiling "$SPEND_CEILING_USD" \
#     --resume outputs/comparison/reviewed/sharks/.../<run-id>
#
# Birds preflight: ./run_full_factorial.sh --task birds --prompt-version v0 --preflight-only
# Optional per-arm controls: --d3-concurrency N --chat-concurrency N
# --luna-concurrency N --microsoft-concurrency N (all default to 1).
# Arms stay sequential. d3 must report N slots and >=8192 context per slot.
# Before a live run, review the chosen task prompts (two for birds, four otherwise),
# commit them together with the code/configuration, verify current provider access,
# billing
# and prices, set OPENAI_API_KEY and OPENROUTER_API_KEY, and start the pinned d3
# server (see docs/D3_LOCAL_MAC.md). The USD ceiling is cumulative across the
# existing outputs/cache ledger; it is not a per-run allowance. Set
# SPEND_CEILING_USD to an amount you approve after reading the current
# preflight estimate. Review label meaning and prompt alignment manually;
# keep the rationale privately and summarise it in the report. Animal and leather
# task mappings propose 1=relevant; confirm this before live runs. Historical
# --label-review files remain optional and are validated when supplied.
# The script checks exact request evidence and shared native-choice content;
# only your review can establish that the Chat wording is a valid analogue.
#
# --preflight-only makes no model calls. It writes a private prompt audit and
# dry-run estimates under outputs/checks/full-factorial/. Live execution first
# copies the existing private comparison outputs to outputs/archive/, then
# writes every setting and model beneath one run directory in
# outputs/comparison/reviewed/<task>/<data-hash>/<version-and-prompt-hash>/.
# Even a fully cached arm gets a new manifest and score snapshot in that folder.
# An interrupted run can be resumed with its exact directory; uncertain cache
# calls still require manual reconciliation and are never replayed automatically.
#
# Expected private tree (the CLI adds <task>/ within each input for animals and
# leather and birds; each shot directory also has a combined prompt-hash suffix):
#   outputs/comparison/reviewed/<task>/<data-hash>/<version-and-prompt-hash>/<run-id>/
#     audit.json                 frozen paths, source/config/prompt/review hashes
#     prompt-audit.txt           readable input-equality checks, no advert text
#     manifest-index.txt        every declared arm with its snapshot/status
#     <input>/[<task>/]<shot>-<prompt-hash>/<arm>/manifest-<id>.json
#     <input>/[<task>/]<shot>-<prompt-hash>/<arm>/scores-<id>.json
#     selection-candidate.yaml  appears after full result coverage
#     <input>/.../table1.csv, table1.md, figure1.png, figure1.svg
# Preflight artefacts, including audit.json, prompt-audit.txt and dry-run
# manifests, stay under outputs/checks/full-factorial/<preflight-id>/.
#
# Read prompt-audit.txt and manifest-index.txt in the run directory. The index
# labels every expected arm, its status, coverage/failures, manifest and cache/new
# counts. Once every arm has full result records (including failures), it creates
# selection-candidate.yaml there. It requires no narrative and never changes
# report/selection.yaml. No HTML preview is generated by inference.
#
# After reviewing coverage, import the candidate and build the site offline:
#   PYTHONPATH=src .venv/bin/python site/build.py import-candidate PATH_TO_CANDIDATE
#   PYTHONPATH=src .venv/bin/python site/build.py build
# Single runs can use site/build.py import-run PATH_TO_MANIFEST instead.
# Imports preserve other datasets and reject conflicting replacements.
#
# Sharks has 16 arms (4 models x 2 prompts x 2 inputs). Animals and leather
# each have 8 title-only arms: leather has no description column and only 10
# of 499 animal rows have descriptions. Task definitions declare the conditions.
# Birds has 4 zero-shot combined-text arms and no published composite baseline.
# The campaign passes --combined-text and --zero-shot; previous task defaults remain.
# Old campaigns with incompatible frozen audits require a new campaign; exact
# cached requests can still be reused without clearing the spend ledger.
# Recorded advert-level failures are always sent for review in policy metrics;
# no probabilities are imputed. CLI exit 2 is accepted only after full snapshot
# validation so later conditions can run. Budgets, uncertain calls, missing billed
# usage, configuration/data errors and interruptions still stop the campaign.
# Failures are never automatically retried. Table coverage counts valid predictions.
# END USAGE
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

if [[ ${1:-} == --help || ${1:-} == -h ]]; then
  sed -n '/^# BEGIN USAGE/,/^# END USAGE/p' "$0" | sed '1d;$d;s/^# //;s/^#$//'
  exit 0
fi

if [[ ! -x .venv/bin/python ]]; then
  printf 'Missing .venv/bin/python; set up the project environment first.\n' >&2
  exit 1
fi

PYTHONPATH=src exec .venv/bin/python -m wildlife_screening.full_factorial "$@"
